import { chmodSync, existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { writeAtomic } from "./core.js";
import { globalCollectionDirectories, inspectCollection, registryPins } from "./collections.js";
import { collectionDecisionScopes } from "./decisions.js";
import { policyFilesHash } from "./collection-files.js";
import { renderScopeContext } from "./agents.js";
import { ownedPath } from "./paths.js";
import { userDirectory } from "./storage.js";

export function installedContext(base: string): { digest: string; contents: string } {
  const collections = registryPins(base).map((pin) => ({
    ...inspectCollection(ownedPath(base, `${pin.id}/${pin.revision}`), pin),
    pin,
    local: true as const,
  }));
  const identities = collections
    .map((entry) => [entry.pin.id, policyFilesHash(entry.files)])
    .sort(([a], [b]) => (String(a) < String(b) ? -1 : String(a) > String(b) ? 1 : 0));
  const digest = createHash("sha256").update(JSON.stringify(identities)).digest("hex");
  const body = renderScopeContext(base, collectionDecisionScopes(collections), 120, true, false);
  return {
    digest,
    contents: body.replace("# Agent context\n", `# Agent context\n\nActive policy fingerprint: \`${digest}\`.\n`),
  };
}

/** Each installation owns its context; system changes do not require rewriting every user's file. */
export function syncLocalContext(base: string): string {
  const path = ownedPath(base, "AGENTS.md");
  writeAtomic(path, installedContext(base).contents);
  if (process.platform !== "win32")
    chmodSync(path, registryPins(base).every((pin) => pin.visibility === "public") ? 0o644 : 0o600);
  syncLocalContextIndex();
  return path;
}

export function syncLocalContextIndex(): string {
  const data = userDirectory("data");
  const base = join(data, "collections");
  const own = ownedPath(base, "AGENTS.md");
  writeAtomic(own, installedContext(base).contents);
  if (process.platform !== "win32") chmodSync(own, 0o600);
  const path = ownedPath(data, "AGENTS.md");
  const sources = globalCollectionDirectories().map(
    (directory) =>
      `- [Local collection context](${join(directory, "AGENTS.md").replaceAll("\\", "/").replaceAll(" ", "%20")}) (read when present).`,
  );
  writeAtomic(
    path,
    `# Local agent context\n\n<!-- Generated by Workbench; edit local collection drafts and obtain approval before activation. -->\n\nObtain human approval of exact local policy changes before activation. Read the existing contexts linked below
and their applicable decision maps before acting. Also read\n\`workbench/.local-collections/AGENTS.md\` in the current checkout when present.\n\n${sources.join("\n")}\n\nBefore project work, run \`workbench collection compatibility check\`. A stale receipt requires reviewing both\npolicy sets and acknowledging their current digest. Report genuine conflicts for human resolution; no source wins\nautomatically. Without Workbench, inspect the current local fingerprints and project records; static files do not\nautomatically detect changes or prove compatibility.\n`,
  );
  if (process.platform !== "win32") chmodSync(path, 0o600);
  return path;
}

export function localContextFresh(base: string): boolean {
  const path = ownedPath(base, "AGENTS.md");
  return existsSync(path) && readFileSync(path, "utf8") === installedContext(base).contents;
}
