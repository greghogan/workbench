import { required } from "./invariants.js";
import { existsSync, lstatSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { readText, writeAtomic } from "./core.js";
import { decisionScopes, localDecisionScopes, type DecisionScope } from "./decisions.js";
import { wrap } from "./formatting.js";
import { hasCollectionProject } from "./collections.js";
import { readConfig } from "./core.js";

export function renderAgentContext(root: string, local = false): string {
  const scopes = local ? localDecisionScopes(root) : decisionScopes(root, false);
  const width = hasCollectionProject(root)
    ? required(required(readConfig(root).markdown, "markdown configuration").wrap_width, "wrap width")
    : 120;
  return renderScopeContext(root, scopes, width, local);
}

export function renderScopeContext(
  root: string,
  scopes: DecisionScope[],
  width: number,
  local: boolean,
  absoluteLinks = local,
): string {
  const link = (label: string, path: string) => {
    return `[${label}](${(absoluteLinks ? path : relative(root, path)).split(sep).join("/").replaceAll(" ", "%20")})`;
  };
  let output = "# Agent context\n\n<!-- Generated by Workbench; edit the source charters and ADRs. -->\n";
  for (const scope of scopes) {
    const applies = scope.appliesTo.includes(".")
      ? "Entire repository"
      : scope.appliesTo.map((path) => `\`${path}/\` and descendants`).join(", ");
    output += `\n## ${scope.source ? `${scope.local ? "Local" : "Project-owned"} ${scope.project.id} decisions` : scope.shared ? "Shared Workbench decisions" : scope.project.id}\n\nApplies to: ${applies}.\n\n`;
    if (scope.source)
      output += `Source: \`${scope.source.id}\`, revision \`${scope.source.revision}\`, SHA-256 \`${scope.source.sha256}\` (${scope.source.visibility}).\n\n`;
    output += `Decision map: ${link(scope.project.id, join(scope.recordsDirectory, "decision-map.md"))}.\n`;
    if (scope.source)
      output += `\n${wrap(`${link("Published collection charter (context)", join(scope.recordsDirectory, "CHARTER.md"))} describes the provider's purpose and boundaries. The consuming project's charter governs adopted and adapted ADRs; this published charter supplies no additional authority.`, width)}\n`;
    if (!scope.shared) {
      const charterPath = join(scope.directory, "workbench/CHARTER.md");
      output += `\n### Charter\n\n`;
      output += existsSync(charterPath)
        ? `${readText(charterPath).trimEnd()}\n`
        : `Charter not yet provided: \`${relative(root, charterPath).split(sep).join("/")}\`.\n`;
    }
    if (scope.decisions.some((decision) => !!decision.instruction)) output += "\n### Agent instructions\n";
    for (const decision of scope.decisions) {
      if (!decision.instruction) continue;
      output += `\n- ${wrap(`${link(decision.reference, decision.path)}: ${decision.instruction}`, width, 2)}\n`;
    }
  }
  // Keep discovery portable: installed policies and machine-specific paths stay out of shared context.
  if (!local) {
    const locations: [string, string][] = [
      ["Explicit user-data override", "$WORKBENCH_DATA_HOME/AGENTS.md"],
      ["Linux", "${XDG_DATA_HOME:-$HOME/.local/share}/workbench/AGENTS.md"],
      ["macOS", "~/Library/Application Support/workbench/AGENTS.md"],
      ["Windows", "%LOCALAPPDATA%/workbench/data/AGENTS.md"],
      ["Checkout", "workbench/.local-collections/AGENTS.md"],
    ];
    output +=
      "\n## Local collections\n\nRead applicable local AGENTS.md files and their linked decision maps when present:\n\n";
    output += locations.map(([label, path]) => `- ${wrap(`${label}: \`${path}\`.`, width, 2)}`).join("\n");
    output += `\n\n${wrap("When Workbench is available, run `workbench collection context` and `workbench collection compatibility check` before acting. Review changed policy sets before acknowledging compatibility; report conflicts for human resolution.", width)}\n`;
  }
  if (local && !scopes.length) output += "\nNo local collections are installed for this checkout.\n";
  return `${output.trimEnd()}\n`;
}

function owned(contents: string): boolean {
  return (
    contents.startsWith("# Agent context\n\n<!-- Generated by Workbench;") ||
    contents.startsWith("# Agent context\n\n## Charter\n\n")
  );
}

export function syncAgents(root: string, checkOnly = false): string[] {
  const path = join(root, "AGENTS.md");
  const expected = renderAgentContext(root);
  let actual: string | undefined;
  if (existsSync(path)) {
    if (!lstatSync(path).isFile() || lstatSync(path).isSymbolicLink())
      throw new Error(`${path}: must be a regular file`);
    actual = readText(path);
  }
  if (actual === expected) return [];
  if (checkOnly) throw new Error(`${path}: generated context is missing or stale; run 'workbench sync'`);
  if (actual && !owned(actual))
    throw new Error(`${path}: existing agent guidance is not Workbench-generated; move it first`);
  writeAtomic(path, expected);
  return [path];
}
