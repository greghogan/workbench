import { required } from "./invariants.js";
import { existsSync, lstatSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { readText, writeAtomic } from "./core.js";
import { decisionScopes } from "./decisions.js";
import { wrap } from "./maps.js";
import { readConfig } from "./core.js";

export function renderAgentContext(root: string): string {
  const scopes = decisionScopes(root);
  const decisions = new Map(
    scopes.flatMap((scope) => scope.decisions.map((decision) => [decision.reference, decision])),
  );
  const width = required(
    required(readConfig(root).markdown, "expected readConfig(root).markdown").wrap_width,
    "expected readConfig(root).markdown!.wrap_width",
  );
  const link = (label: string, path: string) =>
    `[${label}](${relative(root, path).split(sep).join("/").replaceAll(" ", "%20")})`;
  let output = "# Agent context\n\n<!-- Generated by Workbench; edit the source charters and ADRs. -->\n";
  for (const scope of scopes) {
    const applies =
      scope.shared || scope.project.path === "." ? "Entire repository" : `\`${scope.project.path}/\` and descendants`;
    output += `\n## ${scope.shared ? "Shared Workbench decisions" : scope.project.id}\n\nApplies to: ${applies}.\n\n`;
    output += `Decision map: ${link(scope.project.id, join(scope.directory, "workbench/decision-map.md"))}.\n`;
    if (!scope.shared) {
      const charterPath = join(scope.directory, "workbench/CHARTER.md");
      output += `\n### Charter\n\n`;
      output += existsSync(charterPath)
        ? `${readText(charterPath).trimEnd()}\n`
        : `Charter not yet provided: \`${relative(root, charterPath).split(sep).join("/")}\`.\n`;
    }
    if (scope.decisions.some((decision) => !!decision.instruction || decision.overrides.length > 0))
      output += "\n### Agent instructions\n";
    for (const decision of scope.decisions) {
      if (!decision.instruction && !decision.overrides.length) continue;
      output += `\n- ${wrap(`${link(decision.reference, decision.path)}: ${decision.instruction ?? decision.title}`, width, 2)}\n`;
      if (decision.overrides.length) {
        output += `  Overrides in this scope: ${decision.overrides.map((reference) => link(reference, required(decisions.get(reference), "expected decisions.get(reference)").path)).join(", ")}.\n`;
      }
      const replacements = scope.decisions.filter((candidate) => candidate.overrides.includes(decision.reference));
      if (replacements.length) {
        output += `  Replaced in this scope by: ${replacements.map((replacement) => link(replacement.reference, replacement.path)).join(", ")}.\n`;
      }
    }
  }
  return `${output.trimEnd()}\n`;
}

function owned(contents: string): boolean {
  return (
    contents.startsWith("# Agent context\n\n<!-- Generated by Workbench;") ||
    contents.startsWith("# Agent context\n\n## Charter\n\n")
  );
}

export function syncAgents(root: string, checkOnly = false): string[] {
  const path = join(root, "AGENTS.md");
  const expected = renderAgentContext(root);
  let actual: string | undefined;
  if (existsSync(path)) {
    if (!lstatSync(path).isFile() || lstatSync(path).isSymbolicLink())
      throw new Error(`${path}: must be a regular file`);
    actual = readText(path);
  }
  if (actual === expected) return [];
  if (checkOnly) throw new Error(`${path}: generated context is missing or stale; run 'workbench sync'`);
  if (actual && !owned(actual))
    throw new Error(`${path}: existing agent guidance is not Workbench-generated; move it first`);
  writeAtomic(path, expected);
  return [path];
}
